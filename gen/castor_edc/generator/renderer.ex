defmodule CastorEDC.Generator.Renderer do
  @moduledoc """
  Renders the structs of `CastorEDC.Generator.Spec` into formatted Elixir
  source, through the EEx templates in `gen/castor_edc/generator/templates`.

  Every file starts with `banner/0`, which is how the generator recognises
  the files it wrote. The source goes through the project's formatter,
  plugins included, so generated files are exactly what `mix format` makes
  of them, and formatting the project never changes them.
  """

  alias CastorEDC.Generator.Spec
  alias Mix.Tasks.Format

  @templates Path.join(__DIR__, "templates")
  @external_resource Path.join(@templates, "model.ex.eex")
  @external_resource Path.join(@templates, "module.ex.eex")

  @banner """
  # This file is generated by `mix castor_edc.gen.client` from priv/openapi/castor_edc.json.
  # Do not edit it by hand: change the overlay or the generator and run the task again.\
  """

  @doc "The comment every generated file starts with."
  @spec banner() :: String.t()
  def banner, do: @banner

  @doc """
  Renders the module of a model.
  """
  @spec model(Spec.Model.t()) :: String.t()
  def model(%Spec.Model{} = model) do
    @templates
    |> Path.join("model.ex.eex")
    |> EEx.eval_file(model: model)
    |> format()
  end

  @doc """
  Renders the module of an operation group.
  """
  @spec module(Spec.Group.t()) :: String.t()
  def module(%Spec.Group{} = group) do
    @templates
    |> Path.join("module.ex.eex")
    |> EEx.eval_file(group: group)
    |> format()
  end

  @doc false
  # Formats with the project's formatter, plugins included, so generated files
  # are exactly what `mix format` makes of them.
  def format(source) do
    {formatter, _options} = Format.formatter_for_file("lib/castor_edc/generated.ex")
    formatter.(source)
  end

  # Operation helpers the module template calls.

  @doc false
  def group_intro(%Spec.Group{description: description}) when is_binary(description), do: doc(description)
  def group_intro(%Spec.Group{name: name}), do: "Operations of the Castor EDC API on #{humanize(name)}."

  defp humanize(name), do: name |> Macro.underscore() |> String.replace("_", " ")

  @doc false
  def operation_summary(%Spec.Operation{summary: nil}), do: ""
  def operation_summary(%Spec.Operation{summary: summary}), do: " - " <> inline(summary)

  @doc false
  def arity(operation), do: length(argument_names(operation)) + 1

  @doc false
  def arguments(operation, with_default) do
    names = argument_names(operation)
    if with_default, do: Enum.join(names ++ ["opts \\\\ []"], ", "), else: Enum.join(names, ", ")
  end

  defp argument_names(operation) do
    ["client"] ++ Enum.map(operation.path_params, & &1.name) ++ if(operation.body, do: ["body"], else: [])
  end

  @doc false
  def spec_arguments(operation) do
    Enum.join(
      ["CastorEDC.client()"] ++
        Enum.map(operation.path_params, fn _param -> "String.t()" end) ++
        if(operation.body, do: ["map()"], else: []) ++ ["keyword()"],
      ", "
    )
  end

  @doc false
  def result_spec(%Spec.Operation{items: items} = operation) when is_binary(items),
    do: "CastorEDC.Page.t(#{record_spec(operation)})"

  # With `into:`, Req returns what the file was collected into instead.
  def result_spec(%Spec.Operation{decode: nil, accept: "*/*"}), do: "binary() | Collectable.t()"
  def result_spec(%Spec.Operation{decode: nil}), do: "term()"
  def result_spec(%Spec.Operation{decode: module}), do: "#{inspect(module)}.t()"

  @doc false
  def record_spec(%Spec.Operation{decode: nil}), do: "map()"
  def record_spec(%Spec.Operation{decode: module}), do: "#{inspect(module)}.t()"

  @doc false
  def stream_name(%Spec.Operation{name: "list_" <> rest}), do: "stream_" <> rest
  def stream_name(%Spec.Operation{name: name}), do: "stream_" <> name

  @doc false
  def operation_call(operation) do
    path_params = Enum.map_join(operation.path_params, ", ", &"#{inspect(&1.wire)} => #{&1.name}")
    body = if operation.body, do: ", body", else: ""
    ":#{operation.name}, %{#{path_params}}#{body}, opts"
  end

  defp params_encoded(operation, encoding) do
    for %Spec.Param{encoding: ^encoding, name: name} <- operation.query_params, do: String.to_atom(name)
  end

  @doc false
  def operation_pattern(operation) do
    body = if operation.body, do: ", body", else: ""
    ":#{operation.name}, path_params#{body}, opts"
  end

  @doc false
  def operation_body(operation) do
    query_names = Enum.map_join(operation.query_params, ", ", &"#{&1.name}: #{inspect(&1.wire)}")
    list_params = params_encoded(operation, :csv)
    repeated_params = params_encoded(operation, :repeat)
    map_params = params_encoded(operation, :map)
    flag_params = params_encoded(operation, :flag)

    entries = [
      method: inspect(operation.method),
      path: inspect(operation.path),
      path_params: "path_params",
      query: "opts",
      query_names: "%{#{query_names}}",
      list_params: present(list_params),
      repeated_params: present(repeated_params),
      map_params: present(map_params),
      flag_params: present(flag_params),
      body: if(operation.body, do: "body"),
      accept: present(operation.accept),
      items: present(operation.items),
      max_page_size: present(operation.max_page_size),
      not_found_is_empty: present(operation.not_found_is_empty),
      partial_success: present(operation.partial_success),
      fill_items: present(operation.fill_items),
      decode: present(operation.decode)
    ]

    "[" <>
      (entries |> Enum.filter(&elem(&1, 1)) |> Enum.map_join(", ", fn {key, value} -> "#{key}: #{value}" end)) <> "]"
  end

  # The source of an operation's setting, or nil to leave it out.
  defp present(value) when value in [nil, false, [], %{}], do: nil
  defp present(value), do: inspect(value)

  @doc false
  def operation_doc(operation) do
    sections = [
      operation.summary && sentence(operation.summary),
      operation.description && operation.description != operation.summary && operation.description,
      "Sends `#{operation.method |> Atom.to_string() |> String.upcase()} #{operation.path}`. " <>
        "[API reference](#{operation.doc_url})",
      arguments_doc(operation),
      options_doc(operation),
      result_doc(operation)
    ]

    sections |> Enum.filter(&(&1 && String.trim(upstream_text(&1)) != "")) |> Enum.join("\n\n") |> doc()
  end

  defp sentence(text) do
    text = text |> inline() |> String.trim_trailing(".")
    text <> "."
  end

  defp arguments_doc(%Spec.Operation{path_params: [], body: nil}), do: nil

  defp arguments_doc(operation) do
    params = Enum.map(operation.path_params, &("  * `#{&1.name}`" <> description(&1.description)))
    body = if operation.body, do: [body_doc(operation.body)] ++ fill_items_doc(operation), else: []

    Enum.join(["## Arguments", "" | params ++ body], "\n")
  end

  defp fill_items_doc(operation) do
    for {list, keys} <- Enum.sort(operation.fill_items), {key, wire} <- Enum.sort(keys) do
      param = Enum.find(operation.path_params, &(&1.wire == wire))

      "\n    Each item of `#{list}` that has no `#{key}` gets `#{param.name}`, " <>
        "so it doesn't need repeating."
    end
  end

  defp body_doc(body) do
    fields =
      Enum.map(body.fields, fn field ->
        "    * `#{List.first(field.wires)}` (#{field_type_doc(field)})" <> description(field.description)
      end)

    Enum.join(
      [
        "  * `body` - a map, sent as JSON#{if body.description, do: ": " <> inline(body.description), else: ""}"
        | fields
      ],
      "\n"
    )
  end

  defp options_doc(%Spec.Operation{query_params: [], accept: "*/*"}) do
    """
    Every option is passed to `Req`. The file comes back as a binary, unless
    `:into` collects it elsewhere: `into: File.stream!(path)` streams it to
    disk, and the result is then the stream.\
    """
  end

  defp options_doc(%Spec.Operation{query_params: []}), do: "Every option is passed to `Req`."

  defp options_doc(operation) do
    options =
      Enum.map(operation.query_params, fn param ->
        "  * `:#{param.name}` (#{param_type(param, operation)})" <> description(param.description)
      end)

    Enum.join(["## Options", "" | options] ++ ["", "Any other option is passed to `Req`."], "\n")
  end

  defp param_type(param, operation) do
    details =
      Enum.filter(
        [
          param.encoding == :csv && "sent comma-separated",
          param.default != nil && "defaults to `#{inspect(param.default)}`",
          param.wire == "page_size" && operation.max_page_size && "at most `#{operation.max_page_size}`"
        ],
        & &1
      )

    type =
      if param.encoding == :map,
        do: "a map of keys to values, sent as `#{param.wire}[key]=value`",
        else: type_doc(param.type)

    Enum.join([type | details], ", ")
  end

  defp result_doc(%Spec.Operation{items: items} = operation) when is_binary(items) do
    record = if operation.decode, do: "`t:#{inspect(operation.decode)}.t/0`", else: "a map"
    "Returns a `CastorEDC.Page` of #{record} records."
  end

  defp result_doc(%Spec.Operation{partial_success: true}) do
    "Returns what was saved and what wasn't; the `!` variant raises a `CastorEDC.Error` when anything wasn't."
  end

  defp result_doc(_operation), do: nil

  defp description(nil), do: ""
  defp description(text), do: " - " <> inline(text)

  # Helpers the templates call.

  @doc false
  # The top-level keys a model reads.
  def known(model) do
    model.fields |> Enum.flat_map(& &1.wires) |> Enum.reject(&embedded_wire?/1) |> Enum.uniq()
  end

  @doc false
  # The keys under `_embedded` a model reads: those the spec puts there,
  # and those of object fields, which the API often embeds although the
  # spec describes them at the top level.
  def known_embedded(model) do
    model.fields
    |> Enum.flat_map(fn field ->
      embedded = for "_embedded." <> key <- field.wires, do: key
      if object?(field), do: embedded ++ Enum.reject(field.wires, &embedded_wire?/1), else: embedded
    end)
    |> Enum.uniq()
  end

  @doc false
  def field_decode(%Spec.Field{wires: wires, decode: decode} = field) do
    reads = Enum.map(wires, &read/1)

    reads =
      if object?(field),
        do: reads ++ for(wire <- wires, not embedded_wire?(wire), do: read("_embedded." <> wire)),
        else: reads

    value =
      case reads do
        [single] -> single
        several -> "(" <> Enum.join(several, " || ") <> ")"
      end

    case decode do
      :raw -> value
      {:cast, type} -> "CastorEDC.Model.cast(#{value}, #{inspect(type)})"
      {:one, module} -> "CastorEDC.Model.one(#{value}, #{inspect(module)})"
      {:list, module} -> "CastorEDC.Model.list(#{value}, #{inspect(module)})"
    end
  end

  defp object?(%Spec.Field{decode: {kind, _module}}) when kind in [:one, :list], do: true
  defp object?(_field), do: false

  defp read("_embedded." <> key), do: "embedded[#{inspect(key)}]"
  defp read(wire), do: "data[#{inspect(wire)}]"

  defp embedded_wire?(wire), do: String.starts_with?(wire, "_embedded.")

  @doc false
  def field_spec(%Spec.Field{type: type}), do: spec(type)

  defp spec({:list, item}), do: "[#{spec(item)}]"
  defp spec({:model, module}), do: "#{inspect(module)}.t()"
  defp spec({:string, _enum}), do: "String.t()"
  defp spec({:integer, _enum}), do: "integer()"
  defp spec({:number, _enum}), do: "number()"
  defp spec({:boolean, _enum}), do: "boolean()"
  defp spec({:datetime, _enum}), do: "DateTime.t()"
  defp spec({:naive_datetime, _enum}), do: "NaiveDateTime.t()"
  defp spec({:object, _enum}), do: "map()"
  defp spec(_other), do: "term()"

  @doc false
  def field_type_doc(%Spec.Field{type: type, required: required}) do
    if required, do: type_doc(type) <> ", always present", else: type_doc(type)
  end

  @doc false
  def type_doc({:list, item}), do: "list of " <> type_doc(item)
  def type_doc({:model, module}), do: "`t:#{inspect(module)}.t/0`"
  def type_doc({:datetime, _enum}), do: "`DateTime`"
  def type_doc({:naive_datetime, _enum}), do: "`NaiveDateTime`"
  def type_doc({:any, _enum}), do: "any"
  def type_doc({type, nil}), do: Atom.to_string(type)
  def type_doc({type, enum}), do: "#{type}, one of " <> Enum.map_join(enum, ", ", &"`#{&1}`")

  @doc false
  def field_description(%Spec.Field{description: nil}), do: ""
  def field_description(%Spec.Field{description: description}), do: " - " <> inline(description)

  @doc false
  # Text for a heredoc indented by two spaces: no closing delimiter, and
  # every line after the first indented to match.
  def doc(text) do
    text
    |> clean()
    |> String.split("\n")
    |> Enum.map_join("\n", &String.trim_trailing/1)
    |> String.replace(~r/\n(?=.)/, "\n  ")
  end

  defp clean(text) do
    text
    |> upstream_text()
    |> String.replace(~s|"""|, ~s|'''|)
    |> String.trim()
  end

  # The spec's descriptions talk about the HAL format of responses, which the
  # client hides, and use a little HTML, which docs render as Markdown.
  @doc false
  def upstream_text(text) do
    text
    |> String.replace(~r/[^.\n]*\bHalJson\b[^.\n]*\.?/, "")
    |> String.replace(~r"</?b>", "**")
    |> String.replace(~r"</?i>", "_")
    |> String.replace(~r"<br\s*/?>", "\n")
    |> String.replace(~r/[ \t]+\n/, "\n")
    |> String.replace(~r/\n{3,}/, "\n\n")
  end

  # Text for one list item: on one line.
  defp inline(text), do: text |> clean() |> String.replace(~r/\s*\n\s*/, " ")
end
